from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from app.database import get_db
from app.models.user import User, UserRole
from app.models.alert import SecurityAlert, AlertSeverity
from app.schemas.alert import AlertResponse, AlertAcknowledgeRequest
from app.schemas.auth import MessageResponse
from app.core.dependencies import require_roles

router = APIRouter(prefix="/alerts", tags=["Threat Alerts"])


@router.get("/", response_model=List[AlertResponse])
def get_security_alerts(
    severity: Optional[str] = Query(None, description="Filter by severity: LOW, MEDIUM, HIGH, CRITICAL"),
    target_username: Optional[str] = Query(None, description="Filter by target username"),
    is_acknowledged: Optional[bool] = Query(None, description="Filter by acknowledgment status"),
    skip: int = Query(0, ge=0),
    limit: int = Query(50, ge=1, le=200),
    current_user: User = Depends(require_roles(UserRole.ADMIN, UserRole.SECURITY_ANALYST)),
    db: Session = Depends(get_db),
):
    """Retrieve security threat alerts generated by the detection engine."""
    query = db.query(SecurityAlert)
    if severity:
        query = query.filter(SecurityAlert.severity == severity.upper())
    if target_username:
        query = query.filter(SecurityAlert.target_username == target_username)
    if is_acknowledged is not None:
        query = query.filter(SecurityAlert.is_acknowledged == is_acknowledged)

    return query.order_by(SecurityAlert.created_at.desc()).offset(skip).limit(limit).all()


@router.post("/{alert_id}/acknowledge", response_model=AlertResponse)
def acknowledge_alert(
    alert_id: int,
    ack_data: AlertAcknowledgeRequest,
    current_user: User = Depends(require_roles(UserRole.ADMIN, UserRole.SECURITY_ANALYST)),
    db: Session = Depends(get_db),
):
    """Acknowledge or dismiss an alert."""
    alert = db.query(SecurityAlert).filter(SecurityAlert.id == alert_id).first()
    if not alert:
        raise HTTPException(status_code=404, detail="Alert not found.")

    alert.is_acknowledged = ack_data.is_acknowledged
    db.commit()
    db.refresh(alert)
    return alert
